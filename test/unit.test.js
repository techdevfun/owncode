/**
 * Unit tests for owncode signals, verdicts, baselines and config.
 * No network, no git needed: pure functions over synthetic inputs.
 */
import test from "node:test";
import assert from "node:assert/strict";
import {
  parseTrailers,
  isAiAuthor,
  findAgentName,
  detectMarkers,
  detectLicenceHeader,
  isAgentPath,
  isVendorPath,
} from "../dist/signals.js";
import { analyseFile } from "../dist/verdict.js";
import {
  toBaseline,
  diffBaselines,
  newRiskyFiles,
  fixedRiskyFiles,
} from "../dist/baseline.js";
import { loadConfig, matchesIgnore, DEFAULT_CONFIG } from "../dist/config.js";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const HUMAN = {
  sha: "a".repeat(40),
  authorName: "Ada Lovelace",
  authorEmail: "ada@example.com",
  date: "2026-11-16T10:00:00Z",
  message: "Add parser",
};
const AI_TRAILER = {
  sha: "b".repeat(40),
  authorName: "Ada Lovelace",
  authorEmail: "ada@example.com",
  date: "2026-11-16T11:00:00Z",
  message:
    "Add helper\n\nCo-Authored-By: Claude Sonnet 4.5 <noreply@anthropic.com>",
};
const AI_AUTHOR = {
  sha: "c".repeat(40),
  authorName: "Claude",
  authorEmail: "noreply@anthropic.com",
  date: "2026-11-16T12:00:00Z",
  message: "Generate module\n\nGenerated-By: Claude Code",
};
const HEADER = "// SPDX-License-Identifier: MIT\n// Copyright 2026 Example\n";

function ev(commits, content, file = "src/a.ts") {
  return analyseFile({
    file,
    commits,
    content,
    root: "/tmp/fake-root",
    extraMarkers: [],
  });
}

// --- S1: trailers ---------------------------------------------------------
test("trailer: Claude co-author recognised", () => {
  const t = parseTrailers(
    "Fix bug\n\nCo-Authored-By: Claude Sonnet 4.5 <noreply@anthropic.com>",
  );
  assert.equal(t.length, 1);
  assert.equal(t[0].agent, "claude");
});

test("trailer: ChatGPT, Copilot, Codex, Gemini recognised", () => {
  for (const [value, agent] of [
    ["ChatGPT <noreply@openai.com>", "chatgpt"],
    ["GitHub Copilot <copilot@github.com>", "copilot"],
    ["Codex", "codex"],
    ["Gemini CLI", "gemini"],
  ]) {
    const t = parseTrailers(`x\n\nCo-Authored-By: ${value}`);
    assert.equal(t[0].agent, agent, value);
  }
});

test("trailer: Generated-By counts as AI trailer", () => {
  const t = parseTrailers("x\n\nGenerated-By: Claude Code");
  assert.equal(t[0].agent, "claude");
});

test("trailer: Signed-off-by and human co-authors ignored", () => {
  const t = parseTrailers(
    "x\n\nSigned-off-by: Ada <ada@example.com>\nCo-Authored-By: Grace Hopper <grace@example.com>\nReviewed-by: Alan <alan@example.com>",
  );
  assert.equal(t.length, 1); // only the Co-Authored-By line parses...
  assert.equal(t.filter((x) => x.agent !== null).length, 0); // ...but neither is AI
});

test("trailer: unknown agent name in trailer is not AI", () => {
  const t = parseTrailers(
    "x\n\nCo-Authored-By: SomeTool 3000 <tool@example.com>",
  );
  assert.equal(t[0].agent, null);
});

test("isAiAuthor: bare agent names and bot mailboxes", () => {
  assert.equal(isAiAuthor("Claude", "noreply@anthropic.com"), true);
  assert.equal(isAiAuthor("github-actions", "bot@github.com"), true);
  assert.equal(isAiAuthor("Ada Lovelace", "ada@example.com"), false);
  assert.equal(isAiAuthor("Mats Kindahl", "mats@example.com"), false);
});

test("findAgentName: unknown text returns null", () => {
  assert.equal(findAgentName("Ada Lovelace"), null);
  assert.equal(findAgentName("Codex agent run"), "codex");
});

// --- S2: markers ----------------------------------------------------------
test("markers: header AI marker detected", () => {
  const m = detectMarkers("// Generated by Claude Code\nconst x = 1;\n");
  assert.equal(m.length, 1);
  assert.equal(m[0].inHeader, true);
});

test("markers: body marker detected with line number", () => {
  const m = detectMarkers(
    "const a = 1;\n".repeat(50) + "// AI-generated helper below\n",
  );
  assert.equal(m.length, 1);
  assert.equal(m[0].line, 51);
  assert.equal(m[0].inHeader, false);
});

test("markers: DO NOT EDIT banner detected", () => {
  const m = detectMarkers("// DO NOT EDIT - generated file, see schema.json\n");
  assert.equal(m.length, 1);
  assert.equal(m[0].pattern, "do-not-edit-generated");
});

test("markers: auto-generated and this-file-was-generated detected", () => {
  assert.equal(detectMarkers("// auto-generated by protoc\n").length, 1);
  assert.equal(
    detectMarkers("// This file was generated by the build\n").length,
    1,
  );
});

test("markers: normal prose with 'generated' is NOT a marker", () => {
  assert.equal(
    detectMarkers(
      "function generateReport() { return 'generated report'; }\n// regenerated the cache after deploy\n",
    ).length,
    0,
  );
  assert.equal(
    detectMarkers("// This module generates UUIDs for sessions\n").length,
    0,
  );
});

test("markers: extra config patterns extend detection", () => {
  const m = detectMarkers("// written by robo-writer 9000\n", ["robo-writer"]);
  assert.equal(m.length, 1);
  assert.equal(
    detectMarkers("// written by robo-writer 9000\n", ["[invalid("]).length,
    0,
  );
});

// --- S5: licence headers ----------------------------------------------------
test("licence header: SPDX id extracted", () => {
  const h = detectLicenceHeader("// SPDX-License-Identifier: Apache-2.0\n");
  assert.equal(h.spdx, "Apache-2.0");
  assert.equal(h.hasCopyright, false);
});

test("licence header: copyright line counts as header", () => {
  const h = detectLicenceHeader("// Copyright 2026 Example Corp\n");
  assert.equal(h.hasCopyright, true);
  assert.equal(h.spdx, null);
});

test("licence header: absent when neither present", () => {
  const h = detectLicenceHeader("const x = 1;\n");
  assert.equal(h.spdx, null);
  assert.equal(h.hasCopyright, false);
});

// --- S3/S6: paths ------------------------------------------------------------
