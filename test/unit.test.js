// --- Verdicts ------------------------------------------------------------------
test("verdict: human file with header is OWNABLE", () => {
  const r = ev(
    [HUMAN, { ...HUMAN, sha: "d".repeat(40) }],
    HEADER + "const x = 1;\n",
  );
  assert.equal(r.verdict, "OWNABLE");
  assert.equal(r.humanRatio, 1);
});

test("verdict: human file without header is AT-RISK", () => {
  const r = ev([HUMAN, { ...HUMAN, sha: "d".repeat(40) }], "const x = 1;\n");
  assert.equal(r.verdict, "AT-RISK");
  assert.match(r.reasons[0], /licence header/);
});

test("verdict: co-authored file with header, no human edit after, is AT-RISK", () => {
  const r = ev([AI_TRAILER], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "AT-RISK");
  assert.deepEqual(r.agents, ["claude"]);
});

test("verdict: 100% AI, no header is UNPROTECTED", () => {
  const r = ev([AI_AUTHOR], "const x = 1;\n");
  assert.equal(r.verdict, "UNPROTECTED");
  assert.equal(r.humanRatio, 0);
});

test("verdict: 100% AI with header is AT-RISK, not UNPROTECTED", () => {
  const r = ev([AI_AUTHOR], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "AT-RISK");
});

test("verdict: 50/50 human-after-AI with header is OWNABLE", () => {
  // Newest first: human commit on top, AI commit below.
  const r = ev([HUMAN, AI_TRAILER], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "OWNABLE");
  assert.equal(r.humanAfterAi, true);
  assert.equal(r.humanRatio, 0.5);
});

test("verdict: AI commit after the human edit is AT-RISK", () => {
  // Newest first: AI commit on top, human below - no human edit after AI.
  const r = ev([AI_TRAILER, HUMAN], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "AT-RISK");
  assert.equal(r.humanAfterAi, false);
});

test("verdict: single commit, no signals, no header is UNKNOWN", () => {
  const r = ev([HUMAN], "const x = 1;\n");
  assert.equal(r.verdict, "UNKNOWN");
});

test("verdict: single commit with header is OWNABLE (not UNKNOWN)", () => {
  const r = ev([HUMAN], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "OWNABLE");
});

test("verdict: no commits in range is UNKNOWN", () => {
  const r = ev([], HEADER + "const x = 1;\n");
  assert.equal(r.verdict, "UNKNOWN");
});

test("verdict: vendored file without NOTICE is AT-RISK even with header", () => {
  const r = ev(
    [HUMAN, { ...HUMAN, sha: "d".repeat(40) }],
    HEADER + "var x = 1;\n",
    "vendor/legacy.js",
  );
  assert.equal(r.verdict, "AT-RISK");
  assert.equal(r.attributionGap, true);
});

// --- Baselines ---------------------------------------------------------------
function fakeResult(file, verdict) {
  return {
    file,
    verdict,
    humanRatio: 1,
    totalCommits: 2,
    humanCommits: 2,
    aiCommits: 0,
    agents: [],
    markers: [],
    agentPath: false,
    vendorPath: false,
    spdx: "MIT",
    hasCopyright: true,
    headerPresent: true,
    attributionGap: false,
    humanAfterAi: false,
    commitShas: [],
    reasons: [],
  };
}

test("baseline: new risky files detected, fixed files listed", () => {
  const base = toBaseline(
    [fakeResult("a.ts", "OWNABLE"), fakeResult("b.ts", "AT-RISK")],
    "0.1.0",
  );
  const now = [
    fakeResult("a.ts", "AT-RISK"),
    fakeResult("b.ts", "OWNABLE"),
    fakeResult("c.ts", "UNPROTECTED"),
  ];
  const fresh = newRiskyFiles(now, base).map((r) => r.file);
  assert.deepEqual(fresh.sort(), ["a.ts", "c.ts"]);
  assert.deepEqual(fixedRiskyFiles(now, base), ["b.ts"]);
});

test("baseline diff: added / worsened / fixed / unchanged", () => {
  const a = toBaseline(
    [
      fakeResult("w.ts", "OWNABLE"),
      fakeResult("f.ts", "AT-RISK"),
      fakeResult("u.ts", "AT-RISK"),
    ],
    "0.1.0",
  );
  const b = toBaseline(
    [
      fakeResult("w.ts", "UNPROTECTED"),
      fakeResult("f.ts", "OWNABLE"),
      fakeResult("u.ts", "AT-RISK"),
      fakeResult("n.ts", "AT-RISK"),
    ],
    "0.1.0",
  );
  const d = diffBaselines(a, b);
  assert.deepEqual(d.added, ["n.ts"]);
  assert.deepEqual(d.worsened, ["w.ts"]);
  assert.deepEqual(d.fixed, ["f.ts"]);
  assert.deepEqual(d.unchanged, ["u.ts"]);
});

// --- Config ------------------------------------------------------------------
test("config: defaults load when no file exists", () => {
  const dir = mkdtempSync(join(tmpdir(), "owncode-cfg-"));
  const { config, path } = loadConfig(dir);
  assert.equal(path, null);
  assert.equal(config.maxFiles, 2000);
  assert.ok(config.ignore.includes("node_modules/**"));
});

test("config: custom file merges over defaults", () => {
  const dir = mkdtempSync(join(tmpdir(), "owncode-cfg-"));
  writeFileSync(
    join(dir, "owncode.config.json"),
    JSON.stringify({ maxFiles: 10, extraMarkers: ["robo"] }),
  );
  const { config } = loadConfig(dir);
  assert.equal(config.maxFiles, 10);
  assert.deepEqual(config.extraMarkers, ["robo"]);
  assert.equal(config.version, DEFAULT_CONFIG.version);
});

test("config: invalid JSON throws", () => {
  const dir = mkdtempSync(join(tmpdir(), "owncode-cfg-"));
  writeFileSync(join(dir, "owncode.config.json"), "{not json");
  assert.throws(() => loadConfig(dir), /invalid JSON/);
});

test("ignore: dir/**, *.ext and exact paths", () => {
  assert.equal(matchesIgnore("node_modules/a/b.js", ["node_modules/**"]), true);
  assert.equal(matchesIgnore("src/a.min.js", ["*.min.js"]), true);
  assert.equal(matchesIgnore("src/a.js", ["*.min.js"]), false);
  assert.equal(matchesIgnore("package-lock.json", ["package-lock.json"]), true);
  assert.equal(matchesIgnore("src/x.ts", ["dist/**"]), false);
});
